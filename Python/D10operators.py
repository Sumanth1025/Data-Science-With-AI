#Bitwise operators:
#Bitwise and(&):
print(3&4)

#Bitwise or(|):
print(3|4)

#Bitwise xor(^):
print(3^4)

#Bitwise not(~):
print(~3)

#Note: computers doesn't store negative numbers in binary format, so the output of the bitwise not operator is -4.

#Bitwise left shift(<<):
print(3<<1)

#Bitwise right shift(>>):
print(3>>1)
